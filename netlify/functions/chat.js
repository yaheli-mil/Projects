const CANDIDATE_MODELS = [
  "openai/gpt-oss-120b",
  "openai/gpt-oss-20b",
  "qwen/qwen3.8-27b",
  "groq/compound-mini"
];

exports.handler = async function(event, context) {
  const headers = {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Headers": "Content-Type",
    "Access-Control-Allow-Methods": "POST, OPTIONS, GET",
    "Content-Type": "application/json; charset=utf-8"
  };

  if (event.httpMethod === "OPTIONS") {
    return { statusCode: 200, headers, body: "" };
  }

  const rawKey = process.env.GROQ_API_KEY || process.env.GROQ_KEY || "";
  const apiKey = rawKey.trim();

  if (!apiKey) {
    return {
      statusCode: 500,
      headers,
      body: JSON.stringify({
        error: "משתנה הסביבה GROQ_API_KEY אינו מוגדר ב-Netlify."
      })
    };
  }

  if (event.httpMethod === "GET") {
    return {
      statusCode: 200,
      headers,
      body: JSON.stringify({ ok: true, active: true, provider: "groq" })
    };
  }

  if (event.httpMethod !== "POST") {
    return { statusCode: 405, headers, body: JSON.stringify({ error: "Method Not Allowed" }) };
  }

  try {
    const payload = JSON.parse(event.body || "{}");
    const userMessage = payload.message || "";
    const conversationHistory = payload.history || [];

    if (!userMessage) {
      return {
        statusCode: 400,
        headers,
        body: JSON.stringify({ error: "Missing message" })
      };
    }

    const messages = [
      { role: "system", content: TAKAM_SYSTEM_PROMPT }
    ];

    const recentHistory = conversationHistory.slice(-8);
    for (const msg of recentHistory) {
      messages.push({
        role: msg.role === "user" ? "user" : "assistant",
        content: msg.text
      });
    }

    messages.push({
      role: "user",
      content: userMessage
    });

    let lastError = null;
    let successfulReply = null;

    for (const model of CANDIDATE_MODELS) {
      try {
        const apiResponse = await fetch("https://api.groq.com/openai/v1/chat/completions", {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            "Authorization": `Bearer ${apiKey}`
          },
          body: JSON.stringify({
            model: model,
            messages: messages,
            temperature: 0.6,
            max_tokens: 1024
          }),
          signal: AbortSignal.timeout(7000)
        });

        if (apiResponse.ok) {
          const data = await apiResponse.json();
          successfulReply = data.choices?.[0]?.message?.content || "";
          if (successfulReply) break;
        } else {
          const errText = await apiResponse.text();
          lastError = `Status ${apiResponse.status}: ${errText}`;
        }
      } catch (err) {
        lastError = err.message;
      }
    }

    if (!successfulReply) {
      return {
        statusCode: 200,
        headers,
        body: JSON.stringify({
          error: "שגיאה בתקשורת מול Groq API",
          details: lastError
        })
      };
    }

    return {
      statusCode: 200,
      headers,
      body: JSON.stringify({
        reply: successfulReply
      })
    };
  } catch (error) {
    return {
      statusCode: 500,
      headers,
      body: JSON.stringify({
        error: "שגיאה פנימית בפונקציית Netlify",
        details: error.message
      })
    };
  }
};
